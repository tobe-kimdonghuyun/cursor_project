        		text.push(String.fromCodePoint(code));
        		this.Dataset00.addRow();
        		this.Dataset00.setColumn(nChars,0, code.toString(16));
        		this.Dataset00.setColumn(nChars,1, cursor.type);
        		this.Dataset00.setColumn(nChars,2, String.fromCodePoint(code));
        		nChars++;
        		code = this.nextCode(cursor);
