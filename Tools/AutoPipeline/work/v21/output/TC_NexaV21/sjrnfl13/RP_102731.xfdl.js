        this.createCursor = function(code)
        {
        	for(var i = 0; i < this.EastAsianWidth.length; i++) {
        		if(this.EastAsianWidth[i].s <= code && code <= this.EastAsianWidth[i].e) {
        			return {
        				index: i,
        				code: code,
        				segment: this.EastAsianWidth[i],
        				type: this.EastAsianWidth[i].t
        			}
        		}
        		if(code < this.EastAsianWidth[i].s) {
        			return {
        				index: i,
        				code: this.EastAsianWidth[i].s,
        				segment: this.EastAsianWidth[i],
        				type: this.EastAsianWidth[i].t
        			}
        		}
        	}
        	return null;
        }

